def _make_key(bits: int = 2048):
    """Every key in this suite is generated by the test that uses it."""
    return crypto_rsa.generate_private_key(public_exponent=65537, key_size=bits)


def _config_doc(public_key) -> dict:
    der = public_key.public_bytes(
        encoding=serialization.Encoding.DER,
        format=serialization.PublicFormat.SubjectPublicKeyInfo,
    )
    return {"env": {"NEXT_PUBLIC_ENCRYPTION": base64.b64encode(der).decode("ascii")}}


