LOGIN = "theuserid"
STARTED = {"state": {"started": True}}


def _make_key(bits: int = 2048):
    return crypto_rsa.generate_private_key(public_exponent=65537, key_size=bits)


@pytest.fixture(scope="module")
def key():
    return _make_key()


def _spki_doc(public_key) -> dict:
    der = public_key.public_bytes(
        encoding=serialization.Encoding.DER, format=serialization.PublicFormat.SubjectPublicKeyInfo
    )
    return {"env": {"NEXT_PUBLIC_ENCRYPTION": base64.b64encode(der).decode("ascii")}}


def _jwt(payload: dict) -> str:
    def seg(d: dict) -> str:
        return base64.urlsafe_b64encode(json.dumps(d).encode()).decode().rstrip("=")

    return f"{seg({'alg': 'none'})}.{seg(payload)}.signature"


def _account(number: str, currency: str, balance: str = "1.00", kind: str = "SAVINGS", status: str = "ACTIVE") -> dict:
    return {"accountNumber": number, "accountType": kind, "accountStatus": status,
            "accountCurrency": currency, "availableBalance": balance}


def _txn(ref: str, amount: str, ttype: str = "DEBIT", day: str = "23-AUG-2026", sender: str = "SOMEONE") -> str:
    # Hand-written JSON so the amount stays a bare number on the wire, as the bank sends it.
    return (f'{{"transactionReferenceNo":"{ref}","externalRef":null,"transactionAmount":{amount},'
            f'"transactionCurrency":"USD","transactionDate":"{day}","transactionType":"{ttype}",'
            f'"transactionNarration":"ATM WITHDRAWAL","sender":"{sender}","beneficiary":"",'
            f'"transactionCategory":"ATM"}}')


class FakeBank:
    """Serves config, authenticate, accounts and paged transactions; records every request."""

    def __init__(self, private_key, accounts: list[dict], pages: dict[str, list[list[str]]] | None = None,
                 claims: dict | None = None, status: dict[str, int] | None = None):
        self.doc = _spki_doc(private_key.public_key())
        self.private_key = private_key
        self.accounts = accounts
        self.pages = pages or {}
        self.token = _jwt(claims or {"customerId": "123456789", "userId": "bank-side-user"})
        self.status = status or {}
        self.calls: list[tuple[str, dict | None]] = []

    def handle(self, path: str, body: dict | None) -> tuple[int, bytes]:
        self.calls.append((path, body))
        if path in self.status:
            return self.status[path], b"SECRET BODY hunter2"
        if path == ab._PATH_CONFIG:
            return 200, json.dumps(self.doc).encode()
        if path == ab._PATH_AUTHENTICATE:
            return 200, json.dumps({"data": {"idToken": self.token}}).encode()
        if path == ab._PATH_ACCOUNTS:
            return 200, json.dumps({"data": self.accounts}).encode()
        if path == ab._PATH_TRANSACTIONS:
            assert body is not None
            pages = self.pages.get(body["accountNo"], [])
            index = int(body["pageNumber"]) - 1
            rows = pages[index] if index < len(pages) else []
            return 200, ('{"statusCode":200,"description":null,"data":[' + ",".join(rows) + "]}").encode()
        return 404, b""

    def plugin_send(self):
        def send(opener, method, path, body, headers):
            return self.handle(path, json.loads(body) if body else None)

        return patch.object(ab, "_send", send)

    def httpx_client(self):
        def handler(request: httpx.Request) -> httpx.Response:
            status, content = self.handle(request.url.path, json.loads(request.content) if request.content else None)
            return httpx.Response(status, content=content, headers={"content-type": "application/json"})

        transport = httpx.MockTransport(handler)
        return patch.object(
            AccessBankProvider, "_client",
            lambda self: httpx.AsyncClient(transport=transport, base_url=ab.BASE_URL, timeout=30),
        )

    def bodies(self, path: str) -> list[dict]:
        return [body for p, body in self.calls if p == path and body is not None]


def _context(password: str = "hunter2", currencies: str | None = None):
    config = {"import_currencies": currencies} if currencies is not None else {}
    return SimpleNamespace(secrets={"user_id": LOGIN, "password": password}, config=config)


def _sync(bank: FakeBank, params: dict | None = None, **context) -> dict:
    with bank.plugin_send():
        return ab.plugin.sync({**STARTED, **(params or {})}, _context(**context))


def _currencies(result: dict) -> list[str]:
    return [a["currency"] for a in result["data"]["accounts"]]


