def test_only_the_four_paths_can_be_requested():
    """Declared `_PATH_*` globals are exactly the four, and every `/`-leading
    literal in the source is one of them, so an inline path can't slip in."""
    declared = {v for k, v in vars(ab).items() if k.startswith("_PATH_")}
    assert declared == PATHS
    tree = ast.parse((PLUGIN_DIR / "accessbank_plugin.py").read_text())
    literals = {
        node.value for node in ast.walk(tree)
        if isinstance(node, ast.Constant) and isinstance(node.value, str) and node.value.startswith("/")
    }
    assert literals <= declared, f"undeclared path literal(s): {literals - declared}"
    for forbidden in ("transfer", "payment", "beneficiar", "statement", "cheque", "token-request"):
        assert not any(forbidden in literal.lower() for literal in literals)
    assert ab.BASE_URL == "https://ibank.accessbankplc.com"


def test_ssl_context_verifies_and_adds_the_pinned_intermediate():
    ctx = ab._ssl_context()
    assert ctx.verify_mode == ssl.CERT_REQUIRED and ctx.check_hostname
    assert len(ctx.get_ca_certs()) > len(ssl.create_default_context().get_ca_certs())


def test_manifest_is_valid_and_declares_the_bank_host():
    manifest = json.loads((PLUGIN_DIR / "securo-plugin.json").read_text())
    parse_manifest(manifest)
    assert [h["host"] for h in manifest["network"]] == ["ibank.accessbankplc.com"]
    fields = {f["key"]: f for f in manifest["contributes"]["integrations"][0]["fields"]}
    assert fields["user_id"]["secret"] and fields["password"]["secret"]
    assert not fields["import_currencies"].get("secret") and fields["import_currencies"]["required"] is False


def test_the_plugin_loads_in_the_runner_with_the_standard_library_only():
    """`python -I -S` through the runner's own host: no backend packages on the path."""
    host = Path(__file__).resolve().parents[1] / "plugin_runner" / "host.py"
    request = {"method": "sync", "params": STARTED, "secrets": {}, "config": {}}
    out = subprocess.run(
        [sys.executable, "-I", "-S", str(host), str(PLUGIN_DIR), "accessbank_plugin:plugin"],
        input=json.dumps(request), capture_output=True, text=True, timeout=60, check=True,
    )
    reply = json.loads(out.stdout)
    assert reply["ok"] is False and reply["error"]["type"] == "NeedsAuth"


