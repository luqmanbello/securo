@pytest.mark.asyncio
async def test_same_bank_responses_give_the_native_providers_ids_and_money(key):
    """Existing rows move onto the plugin's connection and are matched by
    external_id: the plugin must report what the native provider did."""
    accounts = [_account("0123456789", "NGN", "1500000.00"), _account("9876543210", "USD", "2350.10", kind="CURRENT"),
                _account("5555555555", "EUR", status="DORMANT")]
    pages = {
        "0123456789": [[_txn("NGN-REF-1", "5000.00", "CREDIT", "01-NOV-2026")]],
        "9876543210": [[_txn(f"FT2611{i:06d}", f"{i}.{i % 100:02d}", "DEBIT" if i % 3 else "CREDIT",
                             f"{(i % 28) + 1:02d}-OCT-2026", sender="" if i % 5 == 0 else "ACME LTD")
                        for i in range(20)],
                       [_txn("FT2611LAST", "0.00", "DEBIT", "31-OCT-2026"), _txn("FT2611BIG", "1234567.89")]],
    }
    since = date.today() - timedelta(days=20)
    native_creds = {"user_id": LOGIN, "password_enc": encrypt("hunter2")}

    for currencies in ("USD", ""):
        bank = FakeBank(key, accounts, pages=pages)
        settings = SimpleNamespace(accessbank_import_currencies=currencies)
        with bank.httpx_client(), patch("app.core.config.get_settings", return_value=settings):
            provider = AccessBankProvider()
            native_accounts = await provider.get_accounts(native_creds)
            native = {a.external_id: (a, await provider.get_transactions(native_creds, a.external_id, since))
                      for a in native_accounts}
        native_bodies = bank.bodies(ab._PATH_TRANSACTIONS)

        bank.calls.clear()
        result = _sync(bank, {"since": since.isoformat()}, currencies=currencies)
        payload = parse_payload(result["data"], ["accounts", "transactions"], logos=["accessbank"])
        assert payload is not None
        plugin_bodies = bank.bodies(ab._PATH_TRANSACTIONS)
        assert plugin_bodies == native_bodies

        assert {a.external_id for a in payload.accounts or []} == set(native)
        for account in payload.accounts or []:
            ours = account.to_data()
            theirs, native_txns = native[account.external_id]
            assert (ours.name, ours.type, ours.balance, ours.currency, ours.masked_number) == (
                theirs.name, theirs.type, theirs.balance, theirs.currency, theirs.masked_number)
            plugin_txns = [t.to_data() for t in account.transactions or []]
            assert [(t.external_id, t.amount, t.type, t.date, t.currency, t.payee) for t in plugin_txns] == [
                (t.external_id, t.amount, t.type, t.date, t.currency, t.payee) for t in native_txns]
            assert [t.description for t in plugin_txns] == [t.description for t in native_txns]
            assert all(isinstance(t.amount, Decimal) for t in plugin_txns)
    assert set(native) == {"0123456789", "9876543210"}
